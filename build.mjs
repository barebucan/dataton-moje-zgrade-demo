import {mkdir,writeFile,cp} from 'node:fs/promises';
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
const url="https://github.com/barebucan/dataton-moje-zgrade-demo/releases/download/final-v213-20261108/moje-zgrade-runtime-final-v213.tar.gz";
const response=await fetch(url);if(!response.ok)throw Error('Runtime download failed: '+response.status);
const data=Buffer.from(await response.arrayBuffer());
if(createHash('sha256').update(data).digest('hex')!=="df09da54d963f52e53e036256065f6eecab3aba6326f09f5f0ed2c783e971ad6")throw Error('Runtime integrity check failed');
await writeFile('/tmp/mz-runtime.tar.gz',data);await mkdir('api',{recursive:true});
execFileSync('tar',['-xzf','/tmp/mz-runtime.tar.gz','-C','api']);
await cp('api/runtime/web','public',{recursive:true});
console.log('Final v213 vector buildings, reviewed renewal and flood overview prepared.');
